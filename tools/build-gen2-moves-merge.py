#!/usr/bin/env python3
"""Pokédex Plus — merge the Gen-2 moves data files for the unified gen2 page.

moves-gs.js and moves-crystal.js are both generated by tools/build-moves.py
and BOTH declare `const MD` (single-game pages keep their own MD). The
merged gen2.html needs both games at once, so — mirroring what
tools/build-gen1.py does for the Gen-1 page (MD_RB / MD_Y in moves-gen1.js) —
this tool emits assets/js/moves-gen2.js with:

    const MD_GS      = { ...GOLD/SILVER data... }
    const MD_CRYSTAL = { ...CRYSTAL data... }
    var   MD         = MD_GS;      /* active game, swapped by MovesUI.setGame */

The two source files stay untouched (they are the data of record). Re-run:
    python3 tools/build-gen2-moves-merge.py
"""
import os
import re

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GS = os.path.join(R, 'assets/js/moves-gs.js')
CR = os.path.join(R, 'assets/js/moves-crystal.js')
OUT = os.path.join(R, 'assets/js/moves-gen2.js')

HEADER = '''"use strict";
/* Pokédex Plus — merged Gen-2 moves data (gen2.html).
   Generated by tools/build-gen2-moves-merge.py from moves-gs.js +
   moves-crystal.js (both themselves generated by tools/build-moves.py
   from the pret decompiles) — do not edit by hand.
   MD_GS  = Gold/Silver learnsets (the 1999 pair shares one set),
   MD_CRYSTAL = Crystal learnsets (Move Tutor, a few level-up/egg
   differences). `var MD` points at the ACTIVE game and is swapped by
   MovesUI.setGame() when the theme changes. */
'''


def load_and_rename(path, new_name):
    src = open(path, encoding='utf-8').read()
    # strip the source's own header ("use strict" + comment block) — the
    # merged file carries a single one
    src = src.replace('"use strict";\n', '', 1)
    src = re.sub(r'\A\s*/\*.*?\*/\s*', '', src, count=1, flags=re.S)
    # rename the one and only `const MD = {` declaration
    renamed, n = re.subn(r'\bconst MD\s*=\s*\{', 'const %s = {' % new_name, src, count=1)
    if n != 1:
        raise SystemExit(f'{path}: expected exactly one `const MD = {{`')
    if re.search(r'\bconst MD\b(?!\w)', renamed):
        raise SystemExit(f'{path}: unexpected extra `const MD` reference')
    return renamed.strip()


gs = load_and_rename(GS, 'MD_GS')
cr = load_and_rename(CR, 'MD_CRYSTAL')

out = HEADER + gs + '\n\n' + cr + '\n\nvar MD = MD_GS;\n'
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(out)

# sanity: merged file must parse and expose both consts
import subprocess
JS = (
    'const fs=require("fs"),vm=require("vm");'
    'const ctx={};vm.createContext(ctx);'
    'vm.runInContext(fs.readFileSync(process.argv[1],"utf8"),ctx);'
    'const r=vm.runInContext("JSON.stringify({gs:MD_GS.game,cr:MD_CRYSTAL.game,'
    'active:MD.game,gsN:Object.keys(MD_GS.moves).length,'
    'crN:Object.keys(MD_CRYSTAL.moves).length,'
    'gsLearn:Object.keys(MD_GS.learn).length,'
    'crLearn:Object.keys(MD_CRYSTAL.learn).length})",ctx);'
    'console.log(r);'
)
print(subprocess.run(['node', '-e', JS, OUT], capture_output=True, text=True).stdout.strip())
print(f'wrote {OUT} ({os.path.getsize(OUT)} bytes)')
