#!/usr/bin/env python3
"""Build the merged GENERATION I page data (gen1.html).

gen1.html is ALL of Gen 1 in one dex: the four 1996-99 Game Boy games —
RED, BLUE, GREEN (Japan) and YELLOW — with a theme switcher. This script
merges the per-page sources into the two generated files the page loads:

  assets/js/gen1-data.js    DATA (151 pokemon, base fields from the
                            Red/Blue page + Yellow's own dex texts as
                            ey1/ey2/flavor_fa_y) and SPRITE_SETS
                            (rb, rbc, green, y, yc — every Gen-1 set)
  assets/js/moves-gen1.js   MD_RB + MD_Y (from moves-rb.js /
                            moves-yellow.js) plus a mutable `var MD`
                            that points at the active game's data, so the
                            moves module can swap games with the theme.

Everything else (page logic, css, html) is hand-written and loads these.
Re-run after changing redblue.js / yellow.js / moves-rb.js /
moves-yellow.js.
"""
import json
import os
import re
import sys

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
JS = f'{REPO}/assets/js'

TEXT_FIELDS = ('e1', 'e2', 'flavor_fa')       # yellow's texts are merged in as ey1/ey2/flavor_fa_y


def read(path):
    with open(path, encoding='utf-8') as fh:
        return fh.read()


def grab(src, name):
    """Extract a top-level `const NAME = <json>;` from a page script."""
    m = re.search(r'const ' + name + r' = (\{.*?\}|\[.*?\]);\n', src, re.S)
    if not m:
        sys.exit(f'!! {name} not found')
    return json.loads(m.group(1))


def main():
    rb_src = read(f'{JS}/redblue.js')
    y_src = read(f'{JS}/yellow.js')
    rb = grab(rb_src, 'DATA')
    y = {p['id']: p for p in grab(y_src, 'DATA')}
    rb_sets = grab(rb_src, 'SPRITE_SETS')
    y_sets = grab(y_src, 'SPRITE_SETS')

    # ---- merge DATA: rb base + yellow's own texts --------------------
    merged = []
    for p in rb:
        q = dict(p)
        yp = y[p['id']]
        # sanity: everything except the text fields must agree
        for k in p:
            if k in TEXT_FIELDS:
                continue
            if p[k] != yp[k]:
                sys.exit(f'!! field mismatch #{p["id"]} {k}: {p[k]!r} != {yp[k]!r}')
        q['ey1'], q['ey2'], q['flavor_fa_y'] = yp['e1'], yp['e2'], yp['flavor_fa']
        merged.append(q)

    # ---- sprite sets: rb + green + yellow ----------------------------
    sets = {}
    sets.update(rb_sets)                 # rb, rbc, green
    sets.update(y_sets)                  # y, yc
    for k in sets:                       # verify every referenced file exists
        for bank in ('files', 'back'):
            if bank not in sets[k]:
                continue
            for sub in sets[k][bank].values():
                if isinstance(sub, str):          # color set: {id: path}
                    assert os.path.exists(f'{REPO}/{sub}'), f'missing sprite {sub}'
                else:                             # mono set: {dmg:{id:path}, pocket:{...}}
                    for path in sub.values():
                        assert os.path.exists(f'{REPO}/{path}'), f'missing sprite {path}'

    out = ['"use strict";',
           '/* Pokédex Plus — GENERATION I merged data (gen1.html).',
           '   Generated by tools/build-gen1.py from redblue.js + yellow.js — do not edit.',
           '   e1/e2/flavor_fa   = international Red/Blue texts (also shown for Green,',
           '                      whose own Japanese texts were never translated),',
           '   ey1/ey2/flavor_fa_y = Yellow version texts (all 151 differ from R/B). */',
           'const DATA = ' + json.dumps(merged, ensure_ascii=False, separators=(',', ':')) + ';',
           'const EVOLUTIONS = ' + re.search(r'const EVOLUTIONS = (\{.*?\});\n', rb_src, re.S).group(1) + ';',
           'const SPRITE_SETS = ' + json.dumps(sets, ensure_ascii=False, separators=(',', ':')) + ';',
           '']
    with open(f'{JS}/gen1-data.js', 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(out))
    print(f'gen1-data.js: {len(merged)} pokemon, {len(sets)} sprite sets')

    # ---- merged moves data -------------------------------------------
    mv_rb = read(f'{JS}/moves-rb.js')
    mv_y = read(f'{JS}/moves-yellow.js')

    def body(src):
        m = re.search(r'const MD = (\{.*?\});\s*\Z', src, re.S)
        if not m:
            sys.exit('!! MD not found')
        return m.group(1)

    def relabel(src, label):
        return re.sub(r'label:\s*"[^"]*"', f'label: "{label}"', src, count=1)

    mv_rb = relabel(mv_rb, 'RED/BLUE')     # theme swaps games; keep labels explicit
    mv_y = relabel(mv_y, 'YELLOW')
    out = ['"use strict";',
           '/* Pokédex Plus — merged Gen-1 moves data (gen1.html).',
           '   Generated by tools/build-gen1.py from moves-rb.js + moves-yellow.js — do not edit.',
           '   MD_RB = Red/Blue learnsets (also used for the Green theme — the Japan',
           '   Green version shares the Red/Blue learn tables),',
           '   MD_Y  = Yellow learnsets. `var MD` points at the ACTIVE game and is',
           '   swapped by MovesUI.setGame() when the theme changes. */',
           'const MD_RB = ' + body(mv_rb) + ';',
           'const MD_Y = ' + body(mv_y) + ';',
           'var MD = MD_RB;',
           '']
    with open(f'{JS}/moves-gen1.js', 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(out))
    print('moves-gen1.js: MD_RB + MD_Y ready')
    return 0


if __name__ == '__main__':
    sys.exit(main())
