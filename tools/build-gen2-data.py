#!/usr/bin/env python3
"""Build assets/js/gen2-data.js — the single data file for gen2.html.

Merges the two legacy pages' data into one:
  · assets/js/goldsilver.js  → DATA (251): eg/es EN texts, flavor_fa (G/S FA),
    types (incl. dark/steel), stats, breeding fields, EVOLUTIONS (202 chains)
  · assets/js/crystal.js     → DATA (251): ec EN texts, flavor_fa (Crystal FA)

Output format mirrors gen1-data.js exactly (same field names where possible)
so gen2.js can stay a close sibling of gen1.js:
  DATA          — 251 pokémon, with eg / es / ec pages + flavor_fa /
                  flavor_fa_c Persian texts
  SPRITE_SETS   — g / s / c sprite sets (front+back+shiny variants; c anim)
  EVOLUTIONS    — copied from goldsilver.js
"""
import json
import os

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def extract_block(src, name):
    """Extract `const NAME = <json>;` (array or object) from a JS file."""
    i = src.find('const ' + name + ' =')
    if i < 0:
        return None
    j = i + len('const ' + name + ' =')
    while src[j] in ' \t\n\r':
        j += 1
    opener = src[j]
    closer = {'[': ']', '{': '}'}[opener]
    depth = 0
    in_str = esc = False
    for k in range(j, len(src)):
        c = src[k]
        if in_str:
            if esc:
                esc = False
            elif c == '\\':
                esc = True
            elif c == '"':
                in_str = False
            continue
        if c == '"':
            in_str = True
        elif c == opener:
            depth += 1
        elif c == closer:
            depth -= 1
            if depth == 0:
                return src[j:k + 1]
    return None


def load(path, name):
    src = open(os.path.join(R, path), encoding='utf-8').read()
    return json.loads(extract_block(src, name))


gs = {p['id']: p for p in load('assets/js/goldsilver.js', 'DATA')}
cr = {p['id']: p for p in load('assets/js/crystal.js', 'DATA')}
evolutions = load('assets/js/goldsilver.js', 'EVOLUTIONS')
assert len(gs) == 251 and len(cr) == 251, (len(gs), len(cr))

DATA = []
for pid in range(1, 252):
    g = gs[pid]
    c = cr[pid]
    mon = {
        'id': pid,
        'name': g['name'],
        'display': g['display'],
        'fa': g['fa'],
        'genus': g['genus'],
        'genus_fa': g.get('genus_fa') or '',
        # Gold / Silver / Crystal EN dex texts — list of pages of lines
        'eg': g['eg'],
        'es': g['es'],
        'ec': c['ec'],
        'types': g['types'],
        'stats': g['stats'],
        'height_dm': g['height_dm'],
        'weight_hg': g['weight_hg'],
        # Persian texts: flavor_fa = Gold/Silver wording, flavor_fa_c = Crystal
        'flavor_fa': g.get('flavor_fa') or '',
        'flavor_fa_c': c.get('flavor_fa') or '',
        'abilities': g['abilities'],
        'baseExp': g['baseExp'],
        'capture': g['capture'],
        'happiness': g['happiness'],
        'growth': g['growth'],
        'egg': g['egg'],
        'genderRate': g['genderRate'],
        'habitat': g.get('habitat'),
        'legendary': g.get('legendary', False),
        'mythical': g.get('mythical', False),
    }
    # sanity: crystal must agree on the core numbers
    for k in ('types', 'stats', 'height_dm', 'weight_hg', 'fa'):
        assert g[k] == c[k], f'#{pid} field {k} differs between G/S and C data'
    DATA.append(mon)

# sprite sets — PNG folders; GBC-native colored sets (Gen 2 = Game Boy Color).
# files/back hold {normal:{id:url}, shiny:{id:url}}; anim = animated webp set.
def bank(folder):
    return folder + '/__ID__.png'


SPRITE_SETS = {
    'g': {
        'label': 'Gold', 'color': True,
        'files': {'normal': bank('assets/sprites/gen2-gold'), 'shiny': bank('assets/sprites/gen2-gold-shiny')},
        'back': {'normal': bank('assets/sprites/gen2-gold-back'), 'shiny': bank('assets/sprites/gen2-gold-back-shiny')},
    },
    's': {
        'label': 'Silver', 'color': True,
        'files': {'normal': bank('assets/sprites/gen2-silver'), 'shiny': bank('assets/sprites/gen2-silver-shiny')},
        'back': {'normal': bank('assets/sprites/gen2-silver-back'), 'shiny': bank('assets/sprites/gen2-silver-back-shiny')},
    },
    'c': {
        'label': 'Crystal', 'color': True, 'anim': True,
        'files': {'normal': bank('assets/sprites/gen2-crystal'), 'shiny': bank('assets/sprites/gen2-crystal-shiny')},
        'back': {'normal': bank('assets/sprites/gen2-crystal-back'), 'shiny': bank('assets/sprites/gen2-crystal-back-shiny')},
        'anim': 'assets/sprites/gen2-crystal-anim/__ID__.webp',
    },
}


def js(obj):
    return json.dumps(obj, ensure_ascii=False, separators=(',', ':'))


out = (
    '"use strict";\n'
    '/* ===== Pokédex Plus — GENERATION II data (Gold · Silver · Crystal).\n'
    '   Generated by tools/build-gen2-data.py from the legacy Gold/Silver and\n'
    '   Crystal dex pages — do not edit by hand. 251 Pokémon; eg/es/ec = the\n'
    '   Gold, Silver and Crystal dex texts (EN pages of lines); flavor_fa =\n'
    '   Persian Gold/Silver wording, flavor_fa_c = Persian Crystal wording.\n'
    '   Types include Dark and Steel; stats are the Gen-2 split (Sp.Atk /\n'
    '   Sp.Def). SPRITE_SETS g/s/c = GBC sprite banks with shiny + back\n'
    '   variants; c.anim = Crystal animated battle sprites (webp). ===== */\n'
    'const DATA = ' + js(DATA) + ';\n'
    'const SPRITE_SETS = ' + js(SPRITE_SETS) + ';\n'
    'const EVOLUTIONS = ' + js(evolutions) + ';\n'
)

dst = os.path.join(R, 'assets/js/gen2-data.js')
open(dst, 'w', encoding='utf-8').write(out)
print('wrote', dst, f'{os.path.getsize(dst)/1024:.0f} KB')
print('monn:', len(DATA), '| sets:', list(SPRITE_SETS), '| chains:', len(evolutions['chains']))
# quick integrity: every mon has 3 text versions + fa
for m in DATA:
    assert m['eg'] and m['es'] and m['ec'], m['id']
    assert m['flavor_fa'] and m['flavor_fa_c'], m['id']
print('integrity OK — all 251 have eg/es/ec + both FA texts')
